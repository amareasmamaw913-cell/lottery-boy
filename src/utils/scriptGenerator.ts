import { Scene, RenderStyleConfig } from '../types/storyboard';

export interface ScriptOptions {
  modelName: 'imagen-3.0-generate-002' | 'imagen-3.0-fast-generate-001';
  aspectRatio: '16:9' | '1:1' | '9:16' | '4:3';
  includeSleep: boolean;
  sleepSeconds: number;
  outputDir: string;
  useEnvKey: boolean;
}

export function generatePythonScript(
  scenes: Scene[],
  options: ScriptOptions
): string {
  const promptList = scenes
    .map((s, idx) => `    # Scene ${String(idx + 1).padStart(2, '0')}: ${s.title}\n    ${JSON.stringify(s.prompt)},`)
    .join('\n');

  const apiKeySnippet = options.useEnvKey
    ? `import os

api_key = os.environ.get("GEMINI_API_KEY")
if not api_key:
    raise ValueError("GEMINI_API_KEY environment variable not set. Please set it before running.")

genai.configure(api_key=api_key)`
    : `# Replace with your actual Gemini API key
API_KEY = "YOUR_API_KEY"
genai.configure(api_key=API_KEY)`;

  const sleepImport = options.includeSleep ? 'import time\n' : '';
  const sleepCode = options.includeSleep
    ? `        # Pause ${options.sleepSeconds}s between requests to respect rate limits
        time.sleep(${options.sleepSeconds})
`
    : '';

  return `"""
Minimalist Stickman 30-Scene Batch Imagen Generator
Generated by StickScene Studio
Total Scenes: ${scenes.length}
Aspect Ratio: ${options.aspectRatio}
Model: ${options.modelName}
"""

import os
${sleepImport}import google.generativeai as genai

${apiKeySnippet}

# 30 Curated Scene Prompts
prompts = [
${promptList}
]

# Output directory
output_directory = "${options.outputDir}"
os.makedirs(output_directory, exist_ok=True)

# Initialize Imagen Model
model = genai.GenerativeModel('${options.modelName}')

print(f"Starting batch generation of {len(prompts)} scenes...")

for idx, prompt_text in enumerate(prompts, start=1):
    scene_filename = os.path.join(output_directory, f"scene_{idx:02d}.png")
    
    # Check if already generated to allow resuming
    if os.path.exists(scene_filename):
        print(f"[{idx:02d}/{len(prompts):02d}] Skipping existing {scene_filename}")
        continue

    print(f"[{idx:02d}/{len(prompts):02d}] Generating: {prompt_text[:60]}...")
    try:
        result = model.generate_images(
            prompt=prompt_text,
            number_of_images=1,
            aspect_ratio="${options.aspectRatio}"
        )
        for image in result.images:
            image.save(scene_filename)
            print(f"  --> Saved {scene_filename}")
${sleepCode}
    except Exception as e:
        print(f"  [ERROR] Failed to generate scene_{idx:02d}: {e}")

print("\\nAll scenes processed! Check the folder:", os.path.abspath(output_directory))
`;
}
